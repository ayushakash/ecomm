const request = require('supertest');
const ExcelJS = require('exceljs');
const jwt = require('jsonwebtoken');
const app = require('../server');
const User = require('../models/User');
const Merchant = require('../models/Merchant');
const Category = require('../models/Category');
const Product = require('../models/Product');
const MerchantProduct = require('../models/MerchantProduct');

const token = (userId, extra = {}) =>
  jwt.sign({ userId, ...extra }, process.env.JWT_SECRET || 'your-super-secret-jwt-key', { expiresIn: '1h' });

async function xlsx(sheets) {
  const wb = new ExcelJS.Workbook();
  for (const [name, rows] of Object.entries(sheets)) {
    const ws = wb.addWorksheet(name);
    rows.forEach((r) => ws.addRow(r));
  }
  return Buffer.from(await wb.xlsx.writeBuffer());
}

const binary = (res, cb) => {
  const chunks = [];
  res.on('data', (c) => chunks.push(c));
  res.on('end', () => cb(null, Buffer.concat(chunks)));
};

const PRODUCT_HEADER = ['SKU', 'Name*', 'Description*', 'Category*', 'Brand', 'Unit', 'Price', 'GST Rate', 'Enabled'];
const VARIANT_HEADER = ['Product SKU*', 'Product Name', 'Variant Label*', 'Price*', 'Stock'];

describe('Product Excel import/export', () => {
  let admin; let adminToken; let merchant; let merchantToken; let cement;

  beforeEach(async () => {
    admin = await User.create({ name: 'Admin', email: 'admin@x.com', password: 'secret123', role: 'admin', isActive: true });
    adminToken = token(admin._id);
    merchant = await Merchant.create({
      name: 'Shree Traders', businessName: 'Shree Traders', contactPersonName: 'Ravi', businessType: 'retail',
      phone: '9876543210', area: 'Sector 1', address: 'Main road', city: 'Jaipur', state: 'RJ', pincode: '302001',
      isActive: true, activeStatus: 'approved'
    });
    merchantToken = token(merchant._id);
    cement = await Category.create({ name: 'Cement' });
  });

  const importCatalog = (buf, dryRun) =>
    request(app).post(`/api/product-excel/catalog/import${dryRun ? '?dryRun=true' : ''}`)
      .set('Authorization', `Bearer ${adminToken}`).attach('file', buf, 'products.xlsx');

  it('creates new products, new categories and variants from the sheet', async () => {
    const buf = await xlsx({
      Products: [PRODUCT_HEADER,
        ['', 'UltraTech OPC 53', 'Grade 53 cement', 'cement', 'UltraTech', 'bag', 420, 28, 'Yes'],
        ['TMT-01', 'Kamdhenu TMT', 'Fe500 bars', 'Steel', 'Kamdhenu', 'kg', 65, 18, 'Yes']],
      Variants: [VARIANT_HEADER, ['TMT-01', '', '8mm', 60, 100], ['TMT-01', '', '12mm', 58, 50]],
      Categories: [['Name*', 'Description'], ['Steel', 'Bars and rods']]
    });

    const res = await importCatalog(buf);
    expect(res.status).toBe(200);
    expect(res.body).toMatchObject({ created: 2, updated: 0, categoriesCreated: 1 });

    const cementProduct = await Product.findOne({ name: 'UltraTech OPC 53' });
    expect(String(cementProduct.category)).toBe(String(cement._id)); // case-insensitive category match
    expect(cementProduct.sku).toBe('CEM-ULT-0001'); // generated by the save hook
    const tmt = await Product.findOne({ sku: 'TMT-01' }).populate('category');
    expect(tmt.category.name).toBe('Steel');
    expect(tmt.variants.map((v) => [v.label, v.price, v.stock])).toEqual([['8mm', 60, 100], ['12mm', 58, 50]]);
  });

  it('rejects the whole file when a category, enum or variant link is wrong, and saves nothing', async () => {
    const buf = await xlsx({
      Products: [PRODUCT_HEADER,
        ['', 'Good product', 'ok', 'Cement', '', 'bag', 10, 18, 'Yes'],
        ['', 'Bad category', 'x', 'Paints', '', 'bag', 10, 18, 'Yes'],
        ['', 'Bad unit', 'x', 'Cement', '', 'litre', 10, 7, 'maybe']],
      Variants: [VARIANT_HEADER, ['NOPE-1', '', '8mm', 10, 1]]
    });

    const res = await importCatalog(buf, true);
    expect(res.status).toBe(422);
    const messages = res.body.errors.map((e) => `${e.sheet}:${e.row}:${e.message}`).join('\n');
    expect(messages).toMatch(/Products:3:Category "Paints" does not exist/);
    expect(messages).toMatch(/Products:4:Unit "litre" is invalid/);
    expect(messages).toMatch(/Products:4:GST Rate 7 is invalid/);
    expect(messages).toMatch(/Products:4:Enabled must be Yes or No/);
    expect(messages).toMatch(/Variants:2:Product "NOPE-1" not found/);

    expect((await importCatalog(buf)).status).toBe(422);
    expect(await Product.countDocuments()).toBe(0);
  });

  it('updates existing products by SKU, keeps blank cells, and replaces variants keeping ids of kept labels', async () => {
    const p = await Product.create({
      name: 'Old', description: 'desc', category: cement._id, sku: 'S-1', price: 100,
      variants: [{ label: '8mm', price: 1 }, { label: '10mm', price: 2 }]
    });
    const keptId = String(p.variants[0]._id);
    const buf = await xlsx({
      Products: [PRODUCT_HEADER, ['S-1', 'New name', '', '', '', '', '', '', '']],
      Variants: [VARIANT_HEADER, ['S-1', '', '8MM', 5, 3], ['S-1', '', '16mm', 9, 0], ['S-1', '', '16mm', 9, 0]]
    });
    const dup = await importCatalog(buf);
    expect(dup.status).toBe(422);
    expect(dup.body.errors[0].message).toMatch(/"16mm" is listed twice/);

    const ok = await xlsx({
      Products: [PRODUCT_HEADER, ['S-1', 'New name', '', '', '', '', '', '', '']],
      Variants: [VARIANT_HEADER, ['S-1', '', '8MM', 5, 3], ['S-1', '', '16mm', 9, 0]]
    });
    expect((await importCatalog(ok)).body).toMatchObject({ created: 0, updated: 1 });
    const after = await Product.findById(p._id);
    expect(after.name).toBe('New name');
    expect(after.description).toBe('desc');
    expect(after.price).toBe(100);
    expect(after.variants.map((v) => v.label)).toEqual(['8MM', '16mm']);
    expect(String(after.variants[0]._id)).toBe(keptId);
  });

  it('round-trips the catalog export', async () => {
    await Product.create({ name: 'P', description: 'd', category: cement._id, sku: 'R-1', variants: [{ label: 'A', price: 3 }] });
    const exp = await request(app).get('/api/product-excel/catalog/export')
      .set('Authorization', `Bearer ${adminToken}`).buffer().parse(binary);
    expect(exp.status).toBe(200);
    const res = await importCatalog(exp.body, true);
    expect(res.status).toBe(200);
    expect(res.body.summary).toMatchObject({ productsToCreate: 0, productsToUpdate: 1, variantRows: 1, categoriesToCreate: 0 });
  });

  describe('merchant stock', () => {
    let tmt; let sand;
    beforeEach(async () => {
      tmt = await Product.create({ name: 'TMT', description: 'd', category: cement._id, sku: 'TMT-1', variants: [{ label: '8mm', price: 60 }, { label: '10mm', price: 62 }] });
      sand = await Product.create({ name: 'Sand', description: 'd', category: cement._id, sku: 'SAND-1' });
      await MerchantProduct.create({ merchantId: merchant._id, productId: sand._id, price: 40, stock: 5 });
    });

    const STOCK_HEADER = ['Product SKU*', 'Product Name', 'Category', 'Unit', 'Variant Label', 'Price', 'Stock', 'Enabled'];

    it('merchant updates own stock, adds new catalog products and variant stock; blank rows skipped', async () => {
      const buf = await xlsx({ Stock: [STOCK_HEADER,
        ['SAND-1', '', '', '', '', '', 25, 'No'],
        ['TMT-1', '', '', '', '', 61, 10, 'Yes'],
        ['TMT-1', '', '', '', '8MM', 59, 7],
        ['TMT-1', '', '', '', '10mm', '', ''] // blank → skipped
      ] });
      const res = await request(app).post('/api/product-excel/stock/import')
        .set('Authorization', `Bearer ${merchantToken}`).attach('file', buf, 'stock.xlsx');
      expect(res.status).toBe(200);
      expect(res.body).toMatchObject({ added: 1, updated: 1 });

      const s = await MerchantProduct.findOne({ merchantId: merchant._id, productId: sand._id });
      expect([s.price, s.stock, s.enabled]).toEqual([40, 25, false]);
      const t = await MerchantProduct.findOne({ merchantId: merchant._id, productId: tmt._id });
      expect(t.variantPricing.map((v) => [v.label, v.price, v.stock])).toEqual([['8mm', 59, 7]]);
    });

    it('rejects unknown variants and SKUs', async () => {
      const buf = await xlsx({ Stock: [STOCK_HEADER, ['TMT-1', '', '', '', '20mm', 5, 1], ['XYZ', '', '', '', '', 5, 1]] });
      const res = await request(app).post('/api/product-excel/stock/import')
        .set('Authorization', `Bearer ${merchantToken}`).attach('file', buf, 'stock.xlsx');
      expect(res.status).toBe(422);
      expect(res.body.errors.map((e) => e.message)).toEqual([
        'Variant "20mm" does not exist for TMT-1. Known variants: 8mm, 10mm',
        'SKU "XYZ" is not in the catalog'
      ]);
    });

    it('admin exports and imports stock for a merchant; requires merchantId', async () => {
      const missing = await request(app).get('/api/product-excel/stock/export').set('Authorization', `Bearer ${adminToken}`);
      expect(missing.status).toBe(400);

      const exp = await request(app).get(`/api/product-excel/stock/export?merchantId=${merchant._id}&scope=all`)
        .set('Authorization', `Bearer ${adminToken}`).buffer().parse(binary);
      expect(exp.status).toBe(200);
      const wb = new ExcelJS.Workbook();
      await wb.xlsx.load(exp.body);
      expect(wb.getWorksheet('Stock').rowCount).toBe(5); // header + Sand + TMT + 2 variants

      const buf = await xlsx({ Stock: [STOCK_HEADER, ['SAND-1', '', '', '', '', '', 99, '']] });
      const res = await request(app).post(`/api/product-excel/stock/import?merchantId=${merchant._id}`)
        .set('Authorization', `Bearer ${adminToken}`).attach('file', buf, 'stock.xlsx');
      expect(res.status).toBe(200);
      expect((await MerchantProduct.findOne({ productId: sand._id })).stock).toBe(99);
    });

    it('admin sets stock for a merchant via PUT /:id/stock, linking a new product', async () => {
      const res = await request(app).put(`/api/products/${tmt._id}/stock`)
        .set('Authorization', `Bearer ${adminToken}`).send({ merchantId: String(merchant._id), stock: 12, price: 61 });
      expect(res.status).toBe(200);
      const link = await MerchantProduct.findOne({ merchantId: merchant._id, productId: tmt._id });
      expect([link.stock, link.price]).toEqual([12, 61]);
    });
  });

  describe('impersonation', () => {
    it('admin gets a merchant token; logout with it keeps the merchant session', async () => {
      merchant.refreshToken = 'merchant-refresh';
      await merchant.save();
      const forbidden = await request(app).post(`/api/auth/impersonate/${merchant._id}`).set('Authorization', `Bearer ${merchantToken}`);
      expect(forbidden.status).toBe(403);

      const res = await request(app).post(`/api/auth/impersonate/${merchant._id}`).set('Authorization', `Bearer ${adminToken}`);
      expect(res.status).toBe(200);
      const me = await request(app).get('/api/auth/me').set('Authorization', `Bearer ${res.body.accessToken}`);
      expect(me.body.user.role).toBe('merchant');
      expect(me.body.impersonatedBy).toBe(String(admin._id));

      await request(app).post('/api/auth/logout').set('Authorization', `Bearer ${res.body.accessToken}`);
      expect((await Merchant.findById(merchant._id)).refreshToken).toBe('merchant-refresh');
    });
  });
});
